    # 玩法：玩具推箱子（Sokoban Toy）

    玩家在矩形网格棋盘上操作一个角色，把全部箱子推到目标格即通关。

    ## 规则
    - 玩家每步向 上/下/左/右 移动一格；
    - 目标格是墙则该方向不可走；
    - 目标格有箱子时为"推箱"：仅当箱子身后一格既不是墙也没有其他箱子时才能推；
    - 玩家不能拉箱、不能斜走、不能一次推两箱；
    - 胜利条件：所有箱子都位于目标格上（箱子数与目标数相等）；
    - 没有步数限制、没有道具、没有随机。

    ## 设计要点（出题时遵守）
    - 棋盘必须矩形且四边全为墙；
    - 恰好 1 个玩家起点、至少 1 个箱子、箱子数 = 目标数；
    - 避免把箱子放在角落（上/左或上/右等两侧贴墙且非目标格）——那将不可解；
    - 难度 1：1 箱、直推 ≤2 次；难度 2：1~2 箱、需绕位；难度 3：2~3 箱、需多次绕位或顺序规划。
    """;

